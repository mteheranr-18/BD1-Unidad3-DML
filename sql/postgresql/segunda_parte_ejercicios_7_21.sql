-- EJERCICIO 15: MODIFICAR PRIMARY KEY RELACIONADA

-- Primer intento: ERROR 428C9.
-- La columna es GENERATED ALWAYS AS IDENTITY.

UPDATE clientes
SET id_cliente = 100
WHERE id_cliente = 3
RETURNING *;

-- Consulta de configuracion:

SELECT column_name, is_identity, identity_generation
FROM information_schema.columns
WHERE table_schema = 'public'
AND table_name = 'clientes'
AND column_name = 'id_cliente';

-- Cambio temporal de identidad:

ALTER TABLE clientes
ALTER COLUMN id_cliente
SET GENERATED BY DEFAULT;

-- Segundo intento: ERROR 23503.
-- El cliente tiene pedidos relacionados.

UPDATE clientes
SET id_cliente = 100
WHERE id_cliente = 3
RETURNING *;

-- Restaurar configuracion original:

ALTER TABLE clientes
ALTER COLUMN id_cliente
SET GENERATED ALWAYS;


